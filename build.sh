#!/usr/bin/env bash
# build.sh — builds MLT, the WSOLA command line tool and Catavan (against the local MLT) and starts Catavan.
#
#   ./build.sh                 builds everything and starts Catavan
#   ./build.sh mlt cli ...     builds only the given parts (mlt, cli, kdenlive = Catavan), without starting
#   ./build.sh run             only starts the already built Catavan
#   ./build.sh -- <args>       passes <args> to Catavan (for example a .kdenlive project)
#   ./build.sh --no-run        builds everything without starting
#   ./build.sh --clean         deletes build/ and install/ before building
#
# EXTRA_MODULES=0 ./build.sh mlt   builds MLT without the optional modules (Glaxnimate animations, OpenCV motion
#                                  tracker, RNNoise noise reduction): faster builds while developing. Default: 1.
# NO_INSTALL=1 ./build.sh mlt kdenlive   builds without installing (for example while Catavan is open).
#
# Everything goes to $CATAVAN_BUILD_CACHE (default ~/.cache/catavan-build), outside the source tree.
# After a build, "source ~/.cache/catavan-build/env.sh" puts the local melt, wsola-cli and catavan in the PATH.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=versions.env
source "$HERE/versions.env"

# The real path: when the cache is a symbolic link to another disk, the relative paths that moc generates from the
# link do not resolve (Glaxnimate)
CACHE="$(realpath -m "${CATAVAN_BUILD_CACHE:-$HOME/.cache/catavan-build}")"
BUILD="$CACHE/build"
PREFIX="$CACHE/install"
BUILD_TYPE="${BUILD_TYPE:-RelWithDebInfo}"
JOBS="${JOBS:-$(nproc)}"
# Optional MLT modules. On (1) for the release builds; set the default back to 0 after the release to keep the
# development builds fast (see passo-a-passo.md, reminder after phase 6).
EXTRA_MODULES="${EXTRA_MODULES:-1}"

MLT_SRC="$HERE/src/mlt-$MLT_VERSION"
KDENLIVE_SRC="$HERE/src/kdenlive-$KDENLIVE_VERSION"

log() { printf '\033[1;32m[build]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[build]\033[0m %s\n' "$*" >&2; exit 1; }

targets=()
run=1
app_args=()
while [ $# -gt 0 ]; do
  arg="$1"; shift
  case "$arg" in
    --) app_args=("$@"); break ;;
    --no-run) run=0 ;;
    --clean)  rm -rf "$BUILD" "$PREFIX" ;;
    mlt|cli|kdenlive) targets+=("$arg"); run=0 ;;
    run)      targets=(none) ;;
    -h|--help) sed -n '2,18p' "$0"; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done
[ ${#targets[@]} -gt 0 ] || targets=(mlt cli kdenlive)

[ -d "$MLT_SRC" ] && [ -d "$KDENLIVE_SRC" ] || die "Sources missing; run ./setup.sh first."

write_env() {
  mkdir -p "$PREFIX"
  if [ -n "${MSYSTEM:-}" ]; then
    # Windows: MLT finds lib/mlt and share/mlt relative to the executable, Qt finds bin/data next to it; Qt path
    # lists use Windows paths separated by ';'.
    local win
    win="$(cygpath -m "$PREFIX")"
    cat > "$CACHE/env.sh" <<EOF
# Generated by build.sh — environment to use the local MLT and Catavan.
export CATAVAN_PREFIX="$PREFIX"
export PATH="$PREFIX/bin:\$PATH"
export QT_PLUGIN_PATH="$win/lib/plugins\${QT_PLUGIN_PATH:+;\$QT_PLUGIN_PATH}"
export QML_IMPORT_PATH="$win/lib/qml\${QML_IMPORT_PATH:+;\$QML_IMPORT_PATH}"
EOF
    # Launcher for Windows (double click), without the MSYS2 shell.
    win="$(cygpath -w "$PREFIX")"
    sed 's/$/\r/' > "$CACHE/catavan.cmd" <<EOF
@echo off
set "PATH=$win\\bin;$(cygpath -w "$MINGW_PREFIX/bin");%PATH%"
set "QT_PLUGIN_PATH=$win\\lib\\plugins"
set "QML_IMPORT_PATH=$win\\lib\\qml"
start "" "$win\\bin\\catavan.exe" %*
EOF
    return
  fi
  cat > "$CACHE/env.sh" <<EOF
# Generated by build.sh — environment to use the local MLT and Catavan.
export CATAVAN_PREFIX="$PREFIX"
export PATH="$PREFIX/bin:\$PATH"
export LD_LIBRARY_PATH="$PREFIX/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export MLT_PREFIX="$PREFIX"
export MLT_REPOSITORY="$PREFIX/lib/mlt-7"
export MLT_DATA="$PREFIX/share/mlt-7"
export MLT_PROFILES_PATH="$PREFIX/share/mlt-7/profiles"
export XDG_DATA_DIRS="$PREFIX/share:\${XDG_DATA_DIRS:-/usr/local/share:/usr/share}"
export QT_PLUGIN_PATH="$PREFIX/lib/plugins\${QT_PLUGIN_PATH:+:\$QT_PLUGIN_PATH}"
export QML_IMPORT_PATH="$PREFIX/lib/qml\${QML_IMPORT_PATH:+:\$QML_IMPORT_PATH}"
EOF
}

# cmake_build <name> <source> [flags...]: configures the first time, when build.ninja is missing (e.g. after a
# configure that failed halfway) or when the flags changed, then only rebuilds what changed.
cmake_build() {
  local name="$1" src="$2"; shift 2
  local dir="$BUILD/$name"
  if [ ! -f "$dir/build.ninja" ] || [ "$(cat "$dir/.build-flags" 2>/dev/null)" != "$*" ]; then
    log "Configuring $name"
    cmake -S "$src" -B "$dir" -G Ninja \
      -DCMAKE_BUILD_TYPE="$BUILD_TYPE" \
      -DCMAKE_INSTALL_PREFIX="$PREFIX" \
      -DCMAKE_INSTALL_LIBDIR=lib \
      -DCMAKE_PREFIX_PATH="$PREFIX" \
      "$@"
    printf '%s' "$*" > "$dir/.build-flags"
  fi
  log "Building $name"
  cmake --build "$dir" --parallel "$JOBS"
  # NO_INSTALL=1: build only, e.g. while Catavan is open (installing replaces the libraries it is using)
  [ "${NO_INSTALL:-0}" = 1 ] || cmake --install "$dir" > /dev/null
}

# RNNoise for the MLT module when the system has no package of it (Debian/Ubuntu): a static library with PIC in the
# prefix, linked into the module (nothing to find at run time).
build_rnnoise() {
  export PKG_CONFIG_PATH="$PREFIX/lib/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
  pkg-config --exists rnnoise && return
  local tarball="$CACHE/downloads/$RNNOISE_TARBALL"
  [ -f "$tarball" ] || die "$RNNOISE_TARBALL missing; run ./setup.sh"
  log "Building rnnoise $RNNOISE_VERSION"
  rm -rf "$BUILD/rnnoise"
  mkdir -p "$BUILD/rnnoise"
  tar -xf "$tarball" -C "$BUILD/rnnoise" --strip-components=1
  (cd "$BUILD/rnnoise" && ./configure --prefix="$PREFIX" --libdir="$PREFIX/lib" --disable-shared --enable-static \
     --with-pic --disable-examples --disable-doc > /dev/null && make -j"$JOBS" > /dev/null && make install > /dev/null)
}

build_mlt() {
  local platform=() modules=(-DMOD_RNNOISE=OFF -DMOD_OPENCV=OFF -DMOD_GLAXNIMATE_QT6=OFF)
  # Windows: bin/ + lib/mlt layout (MLT finds its modules relative to the executable); no movit package in MSYS2.
  [ -z "${MSYSTEM:-}" ] || platform=(-DWINDOWS_DEPLOY=OFF -DMOD_MOVIT=OFF)
  if [ "$EXTRA_MODULES" = 1 ]; then
    build_rnnoise
    modules=(-DMOD_RNNOISE=ON -DMOD_OPENCV=ON -DMOD_GLAXNIMATE_QT6=ON)
  fi
  cmake_build mlt "$MLT_SRC" \
    -DCLANG_FORMAT=OFF -DBUILD_TESTING=OFF -DBUILD_DOCS=OFF \
    -DMOD_XINE=OFF -DMOD_NDI=OFF -DSWIG_PYTHON=OFF "${modules[@]}" "${platform[@]}"
  if [ -n "${MSYSTEM:-}" ]; then
    # Windows: MLT only looks for frei0r plugins in lib/frei0r-1 next to the executable (no FREI0R_PATH)
    mkdir -p "$PREFIX/lib/frei0r-1"
    cp -u "$MINGW_PREFIX"/lib/frei0r-1/*.dll "$PREFIX/lib/frei0r-1/"
  fi
}

build_cli() {
  cmake_build wsola-cli "$HERE/tools/wsola-cli" -DWSOLA_DIR="$MLT_SRC/src/modules/wsola"
}

build_kdenlive() {
  [ -f "$PREFIX/lib/cmake/Mlt7/Mlt7Config.cmake" ] || die "Local MLT not installed; run ./build.sh mlt"
  local platform=()
  # Windows: the newer qmllint of MSYS2 (Qt 6.12) fails on upstream QML (confusing-expression-statement).
  [ -z "${MSYSTEM:-}" ] || platform=(-DBUILD_RUN_QMLLINT=OFF)
  cmake_build kdenlive "$KDENLIVE_SRC" \
    -DBUILD_TESTING=OFF -DKDE_INSTALL_USE_QT_SYS_PATHS=OFF -DMlt7_DIR="$PREFIX/lib/cmake/Mlt7" "${platform[@]}"
}

write_env
for t in "${targets[@]}"; do
  case "$t" in
    mlt) build_mlt ;;
    cli) build_cli ;;
    kdenlive) build_kdenlive ;;
  esac
done

if [ "$run" -eq 1 ]; then
  [ -x "$PREFIX/bin/catavan" ] || die "Catavan is not built yet."
  # shellcheck disable=SC1091
  source "$CACHE/env.sh"
  log "Starting Catavan (local MLT in $PREFIX)"
  exec "$PREFIX/bin/catavan" "${app_args[@]}"
fi
